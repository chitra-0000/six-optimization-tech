package com.bnpp.regliss.six.it;

import org.springframework.beans.factory.config.BeanPostProcessor;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.context.annotation.Bean;

import javax.sql.DataSource;
import java.lang.reflect.InvocationHandler;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.lang.reflect.Proxy;
import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Test only. Lets the SIX integration tests run on the H2 test database (MODE=Oracle) without changing any
 * production class: the SQL the SIX classes send is rewritten into its H2 equivalent before H2 parses it.
 * Nothing is rewritten when the test database is a real Oracle.
 *
 * <ul>
 *   <li>{@code FOR UPDATE SKIP LOCKED} - {@code FOR UPDATE} (same result with one test thread holding the locks)</li>
 *   <li>{@code TO_NUMBER(x DEFAULT NULL ON CONVERSION ERROR)} - {@code SIX_IT_TO_NUMBER(x)}: number, or null when not numeric</li>
 *   <li>{@code seq.NEXTVAL FROM DUAL CONNECT BY LEVEL <= ?} - {@code seq.NEXTVAL FROM SYSTEM_RANGE(1, ?)}</li>
 *   <li>the identity-sequence lookup in {@code ALL_TAB_IDENTITY_COLS} - the same lookup in H2's INFORMATION_SCHEMA</li>
 *   <li>{@code generated as identity} (Hibernate's Oracle12cDialect DDL for the SIX tables, which H2 refuses) -
 *       {@code generated by default as identity}, as in the V2_46x scripts. Without it Hibernate cannot create
 *       SIX_INSTRUMENTS, SIX_TARGET, FILTERED_SIX_*, SIX_FILTERED_POLLER ... in H2.</li>
 *   <li>the foreign keys of SIX_TARGET / FILTERED_SIX_TARGET created by Hibernate get {@code ON DELETE CASCADE}, as in
 *       V2_469 / V2_470 (the SIX deletes rely on it)</li>
 *   <li>{@code LOCK TABLE x IN EXCLUSIVE MODE NOWAIT} (no LOCK TABLE in H2) - a plain read of the table</li>
 * </ul>
 */
@TestConfiguration
public class SixH2Compatibility {

    static final String TO_NUMBER_FUNCTION = "SIX_IT_TO_NUMBER";

    private static final Pattern SKIP_LOCKED = Pattern.compile("\\s+SKIP\\s+LOCKED", Pattern.CASE_INSENSITIVE);
    private static final Pattern SAFE_TO_NUMBER = Pattern.compile(
            "TO_NUMBER\\(\\s*([^()]+?)\\s+DEFAULT\\s+NULL\\s+ON\\s+CONVERSION\\s+ERROR\\s*\\)", Pattern.CASE_INSENSITIVE);
    private static final Pattern IDENTITY_DDL = Pattern.compile("\\bgenerated\\s+as\\s+identity\\b", Pattern.CASE_INSENSITIVE);
    private static final Pattern TARGET_FOREIGN_KEY = Pattern.compile(
            "^(\\s*alter\\s+table\\s+(?:filtered_)?six_target\\s+add\\s+constraint\\s+\\w+\\s+foreign\\s+key\\s*\\(\\w+\\)"
                    + "\\s*references\\s+\\w+)\\s*$", Pattern.CASE_INSENSITIVE);
    private static final Pattern LOCK_TABLE = Pattern.compile(
            "^\\s*LOCK\\s+TABLE\\s+(\\w+)\\s+IN\\s+EXCLUSIVE\\s+MODE(\\s+NOWAIT)?\\s*$", Pattern.CASE_INSENSITIVE);
    private static final Pattern ROW_GENERATOR = Pattern.compile(
            "\\.NEXTVAL\\s+FROM\\s+DUAL\\s+CONNECT\\s+BY\\s+LEVEL\\s*<=\\s*\\?", Pattern.CASE_INSENSITIVE);
    private static final String ORACLE_IDENTITY_LOOKUP = "SELECT OWNER, SEQUENCE_NAME FROM ALL_TAB_IDENTITY_COLS";
    private static final String H2_IDENTITY_LOOKUP = "SELECT TABLE_SCHEMA AS OWNER, SEQUENCE_NAME FROM INFORMATION_SCHEMA.COLUMNS"
            + " WHERE TABLE_SCHEMA = SCHEMA() AND TABLE_NAME = ? AND COLUMN_NAME = 'ID' AND SEQUENCE_NAME IS NOT NULL";

    /** Wraps the DataSource bean (H2 only). Static: a BeanPostProcessor must not wait for this configuration bean. */
    @Bean
    public static BeanPostProcessor sixH2DataSourceAdapter() {
        return new BeanPostProcessor() {
            @Override
            public Object postProcessAfterInitialization(Object bean, String beanName) {
                return bean instanceof DataSource ? wrap((DataSource) bean) : bean;
            }
        };
    }

    /** H2 function behind {@link #TO_NUMBER_FUNCTION} (Oracle: TO_NUMBER(x DEFAULT NULL ON CONVERSION ERROR)). */
    public static BigDecimal toNumberOrNull(String value) {
        if (value == null || value.trim().isEmpty()) {
            return null;
        }
        try {
            return new BigDecimal(value.trim());
        } catch (NumberFormatException notNumeric) {
            return null;
        }
    }

    static String rewrite(String sql) {
        if (sql == null) {
            return null;
        }
        String out = sql;
        if (out.trim().toUpperCase(Locale.ROOT).startsWith(ORACLE_IDENTITY_LOOKUP)) {
            return H2_IDENTITY_LOOKUP;
        }
        out = IDENTITY_DDL.matcher(out).replaceAll("generated by default as identity");
        out = TARGET_FOREIGN_KEY.matcher(out).replaceAll("$1 on delete cascade");
        out = LOCK_TABLE.matcher(out).replaceAll("SELECT COUNT(*) FROM $1");
        out = SKIP_LOCKED.matcher(out).replaceAll("");
        out = ROW_GENERATOR.matcher(out).replaceAll(".NEXTVAL FROM SYSTEM_RANGE(1, ?)");
        Matcher toNumber = SAFE_TO_NUMBER.matcher(out);
        out = toNumber.replaceAll(TO_NUMBER_FUNCTION + "($1)");
        return out;
    }

    static DataSource wrap(DataSource target) {
        H2State state = new H2State();
        return (DataSource) Proxy.newProxyInstance(SixH2Compatibility.class.getClassLoader(), new Class<?>[]{DataSource.class},
                (proxy, method, args) -> {
                    Object result = invoke(target, method, args);
                    if (result instanceof Connection && state.isH2((Connection) result)) {
                        return proxy(Connection.class, result, state);
                    }
                    return result;
                });
    }

    private static Object proxy(Class<?> type, Object target, H2State state) {
        InvocationHandler handler = (p, method, args) -> {
            if (args != null && args.length > 0 && args[0] instanceof String && rewritesFirstArgument(method.getName())) {
                args[0] = rewrite((String) args[0]);
            }
            Object result = invoke(target, method, args);
            if (result instanceof Statement && !(result instanceof PreparedStatement)) {
                return proxy(Statement.class, result, state);
            }
            return result;
        };
        return Proxy.newProxyInstance(SixH2Compatibility.class.getClassLoader(), new Class<?>[]{type}, handler);
    }

    private static boolean rewritesFirstArgument(String method) {
        return method.startsWith("prepare") || method.startsWith("execute") || "addBatch".equals(method) || "nativeSQL".equals(method);
    }

    private static Object invoke(Object target, Method method, Object[] args) throws Throwable {
        try {
            return method.invoke(target, args);
        } catch (InvocationTargetException e) {
            throw e.getTargetException();
        }
    }

    /** Detects H2 once and creates the H2 function the rewritten SQL uses. */
    private static final class H2State {
        private volatile Boolean h2;

        boolean isH2(Connection connection) throws SQLException {
            Boolean known = h2;
            if (known == null) {
                synchronized (this) {
                    if (h2 == null) {
                        h2 = connection.getMetaData().getURL().startsWith("jdbc:h2:");
                        if (h2) {
                            try (Statement statement = connection.createStatement()) {
                                statement.execute("CREATE ALIAS IF NOT EXISTS " + TO_NUMBER_FUNCTION + " FOR \""
                                        + SixH2Compatibility.class.getName() + ".toNumberOrNull\"");
                            }
                        }
                    }
                    known = h2;
                }
            }
            return known;
        }
    }
}
